void StrokeSvg(ImDrawList* dl, const char* svg, ImVec2 origin, float scale, float thickness,
               ImU32 col, bool roundCaps) {
    for (const Sub& sub : Parse(svg, origin, scale))
        StrokeSub(dl, sub, thickness, col, roundCaps);
}

void DrawRail(ImDrawList* dl, Rail id, ImVec2 center, float scale, ImU32 col) {
    const RailIcon& ic = kRail[(int)id];
    ImVec2 box(center.x - 11.5f * scale, center.y - 11.5f * scale);
    StrokeSvg(dl, ic.path, ImVec2(box.x + ic.x * scale, box.y + ic.y * scale), scale, 1.4f * scale,
              col, true);
}

