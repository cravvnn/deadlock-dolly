std::vector<Sub> Parse(const char* s, ImVec2 origin, float scale) {
    std::vector<Sub> subs;
    ImVec2 cur(0, 0);
    char cmd = 0;
    auto num = [&](float& v) -> bool {
        while (*s == ' ' || *s == ',')
            ++s;
        char* end = nullptr;
        v = strtof(s, &end);
        if (end == s)
            return false;
        s = end;
        return true;
    };
    auto map = [&](float x, float y) { return ImVec2(origin.x + x * scale, origin.y + y * scale); };
    auto add = [&](ImVec2 p) {
        if (subs.empty())
            subs.emplace_back();
        auto& v = subs.back().pts;
        if (v.empty() || std::fabs(v.back().x - p.x) + std::fabs(v.back().y - p.y) > 0.01f)
            v.push_back(p);
    };
    while (*s) {
        while (*s == ' ' || *s == ',')
            ++s;
        if (!*s)
            break;
        if ((*s >= 'A' && *s <= 'Z') || (*s >= 'a' && *s <= 'z'))
            cmd = *s++;
        float x, y, x1, y1, x2, y2;
        if (cmd == 'M') {
            if (!num(x) || !num(y))
                break;
            subs.emplace_back();
            cur = ImVec2(x, y);
            add(map(x, y));
            cmd = 'L'; // implicit lineto after moveto
        } else if (cmd == 'L') {
            if (!num(x) || !num(y))
                break;
            cur = ImVec2(x, y);
            add(map(x, y));
        } else if (cmd == 'C') {
            if (!num(x1) || !num(y1) || !num(x2) || !num(y2) || !num(x) || !num(y))
                break;
            ImVec2 p0 = cur, p1(x1, y1), p2(x2, y2), p3(x, y);
            float len =
                (std::hypot(p1.x - p0.x, p1.y - p0.y) + std::hypot(p2.x - p1.x, p2.y - p1.y) +
                 std::hypot(p3.x - p2.x, p3.y - p2.y)) *
                scale;
            int n = (int)std::ceil(len / 1.5f);
            n = n < 4 ? 4 : (n > 32 ? 32 : n);
            for (int i = 1; i <= n; ++i) {
                float t = (float)i / n, u = 1 - t;
                float bx = u * u * u * p0.x + 3 * u * u * t * p1.x + 3 * u * t * t * p2.x +
                           t * t * t * p3.x;
                float by = u * u * u * p0.y + 3 * u * u * t * p1.y + 3 * u * t * t * p2.y +
                           t * t * t * p3.y;
                add(map(bx, by));
            }
            cur = p3;
        } else if (cmd == 'Z' || cmd == 'z') {
            if (!subs.empty()) {
                auto& sub = subs.back();
                if (sub.pts.size() > 2 && std::fabs(sub.pts.front().x - sub.pts.back().x) +
                                                  std::fabs(sub.pts.front().y - sub.pts.back().y) <
                                              0.01f)
                    sub.pts.pop_back();
                sub.closed = true;
            }
            cmd = 0;
        } else {
            ++s; // unsupported command: skip
        }
    }
    return subs;
}

bool Sharp(ImVec2 a, ImVec2 b, ImVec2 c) {
    ImVec2 d1(b.x - a.x, b.y - a.y), d2(c.x - b.x, c.y - b.y);
    float l1 = std::hypot(d1.x, d1.y), l2 = std::hypot(d2.x, d2.y);
    if (l1 < 1e-4f || l2 < 1e-4f)
        return false;
    float cosA = (d1.x * d2.x + d1.y * d2.y) / (l1 * l2);
    return cosA < 0.77f; // turn sharper than ~40 degrees
}

void StrokeSub(ImDrawList* dl, const Sub& sub, float th, ImU32 col, bool caps) {
    const auto& p = sub.pts;
    const int n = (int)p.size();
    if (n < 2)
        return;
    const float r = th * 0.5f;
    std::vector<int> corners;
    for (int i = 0; i < n; ++i) {
        if (!sub.closed && (i == 0 || i == n - 1))
            continue;
        if (Sharp(p[(i - 1 + n) % n], p[i], p[(i + 1) % n]))
            corners.push_back(i);
    }
    auto stroke = [&](int from, int count, bool closed) {
        dl->PathClear();
        for (int k = 0; k < count; ++k)
            dl->PathLineTo(p[(from + k) % n]);
        dl->PathStroke(col, closed ? ImDrawFlags_Closed : 0, th);
    };
    if (corners.empty()) {
        stroke(0, n, sub.closed);
    } else if (sub.closed) {
        for (size_t c = 0; c < corners.size(); ++c) {
            int a = corners[c], b = corners[(c + 1) % corners.size()];
            int count = ((b - a + n) % n) + 1;
            if (corners.size() == 1)
                count = n + 1;
            stroke(a, count, false);
        }
    } else {
        int start = 0;
        for (int c : corners) {
            stroke(start, c - start + 1, false);
            start = c;
        }
        stroke(start, n - start, false);
    }
    for (int c : corners)
        dl->AddCircleFilled(p[c], r, col, 12);
    if (!sub.closed && caps) {
        dl->AddCircleFilled(p[0], r, col, 12);
        dl->AddCircleFilled(p[n - 1], r, col, 12);
    }
}

